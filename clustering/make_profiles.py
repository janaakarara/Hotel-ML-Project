from pathlib import Path
import numpy as np, pandas as pd
ROOT = Path(__file__).resolve().parents[1]
raw = pd.read_csv(ROOT / "data/processed/h2_clustering_stage2.csv")
post = pd.read_csv(ROOT / "data/processed/h2_clustering_profile_cols.csv")
assert len(raw) == len(post)
raw["Nights"] = raw["StaysInWeekNights"] + raw["StaysInWeekendNights"]
raw["HasChildren"] = (raw["Children"] > 0).astype(int)
CATS = ["MarketSegment", "Country", "Meal", "CustomerType", "ReservedRoomType"]

MARK = "=== CLUSTER DESCRIPTIONS ==="
OLD_MARK = "=== CLUSTER STANDOUT COLUMNS ==="
def _w(v, a, up, down):
    d = (v - a) / a if a else 0
    f = f"{a:.1f}" if a < 10 else f"{a:.0f}"
    return f"{up}, avg {f}" if d >= .10 else f"{down}, avg {f}" if d <= -.10 else "about average"

def append_standouts(prof, path):
    df = prof.reset_index(); w = df["rows"]
    num = ["lead_time_mean", "nights_mean", "adults_mean", "pct_children", "posthoc_adr_mean", "posthoc_cancel_rate_pct"]
    cats = [c for c in df.columns if c.startswith("top_")]
    L = [MARK, "Generated by fixed rules from cluster_profiles.csv (same data -> same text). avg = average over all rows;",
         "'earlier/longer/higher...' = at least 10% away from that average. Not used to cluster: ADR and cancellation."]
    if len(df) > 15:
        L.append(f"skipped: {len(df)} clusters is too many to describe")
    else:
        avg = {c: (df[c] * w).sum() / w.sum() for c in num}
        mode = {c: df.groupby(c)["rows"].sum().idxmax() for c in cats}
        for _, r in df.iterrows():
            a = max(1, round(r.adults_mean)); q = r.pct_children
            kids = ("every booking has children" if q >= 99 else "mostly bookings with children" if q >= 50
                    else "no children" if q < 1 else "almost no children" if q < 10 else f"{q:.0f}% of bookings have children")
            diffs = [f"{c[4:]} {r[c]} (overall {mode[c]})" for c in cats if r[c] != mode[c]]
            s1 = (f"C{int(r['cluster'])} ({r['share_pct']}% of bookings, {int(r['rows'])} rows): about {a} adult{'s' if a != 1 else ''}, {kids}; "
                  f"books about {r.lead_time_mean:.0f} days ahead ({_w(r.lead_time_mean, avg['lead_time_mean'], 'earlier than average', 'later than average')}) "
                  f"and stays {r.nights_mean:.1f} nights ({_w(r.nights_mean, avg['nights_mean'], 'longer than average', 'shorter than average')}).")
            s2 = ("Most common " + "; ".join(diffs) + ".") if diffs else "Its most common categories are the same as overall."
            s3 = (f"Afterwards (not used to cluster): ADR {r.posthoc_adr_mean:.0f} ({_w(r.posthoc_adr_mean, avg['posthoc_adr_mean'], 'higher', 'lower')}), "
                  f"cancellation {r.posthoc_cancel_rate_pct:.0f}% ({_w(r.posthoc_cancel_rate_pct, avg['posthoc_cancel_rate_pct'], 'higher', 'lower')}).")
            L.append(" ".join([s1, s2, s3]))
    t = path.read_text(encoding="utf-8") if path.exists() else ""
    for m in (MARK, OLD_MARK):
        i = t.find(m)
        if i >= 0: t = t[:i]
    path.write_text(t.rstrip("\n") + "\n\n" + "\n".join(L) + "\n", encoding="utf-8")

for p in sorted((ROOT / "clustering").glob("*/*/outputs/labels.npy")):
    lab = np.load(p)
    if len(lab) != len(raw):
        print("skip (row count differs):", p); continue
    g = raw.assign(cluster=lab).groupby("cluster")
    ph = post.assign(cluster=lab).groupby("cluster")
    out = pd.DataFrame({"rows": g.size()})
    out["share_pct"] = out["rows"] / len(raw) * 100
    out["lead_time_mean"] = g["LeadTime"].mean()
    out["nights_mean"] = g["Nights"].mean()
    out["adults_mean"] = g["Adults"].mean()
    out["pct_children"] = g["HasChildren"].mean() * 100
    for c in CATS:
        out["top_" + c] = g[c].agg(lambda s: s.value_counts().index[0])
    out["posthoc_adr_mean"] = ph["ADR"].mean()
    out["posthoc_cancel_rate_pct"] = ph["IsCanceled"].mean() * 100
    out.round(2).to_csv(p.parent / "cluster_profiles.csv")
    append_standouts(out.round(2), p.parent / "results.txt")
    print("wrote", p.parent / "cluster_profiles.csv")
